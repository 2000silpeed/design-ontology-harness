# Adapter class


class RawCssVariablesAdapter(StackAdapter):
    id: str = ADAPTER_ID
    version: str = ADAPTER_VERSION
    supported_preset_api: str = SUPPORTED_PRESET_API

    def detect(self, target_repo: Path) -> float:
        score = 0.5
        pkg = target_repo / "package.json"
        if not pkg.exists():
            score = 0.6

        has_tailwind = any(
            (target_repo / f"tailwind.config.{ext}").exists()
            for ext in ("ts", "mts", "cts", "js", "mjs", "cjs")
        )
        has_components_json = (target_repo / "components.json").exists()
        if not has_tailwind and not has_components_json:
            score += 0.1

        return round(min(score, 1.0), 3)

    def render(
        self,
        preset: PresetBundle,
        target_repo: Path,
        color_mode: str,
        locale: str = "en",
    ) -> list[FileOp]:
        supported_modes = preset.color_modes or [preset.default_color_mode]
        if color_mode not in supported_modes:
            raise ValueError(
                f"preset {preset.id} does not support color_mode='{color_mode}' "
                f"(supported: {supported_modes})"
            )

        pairing = resolve_locale_pairing(preset, locale) if locale != "en" else None
        has_fonts_css = locale == "ko" and pairing is not None

        ops: list[FileOp] = []
        ops.append(
            FileOp(
                path="design-system/tokens.css",
                content=_build_tokens_css(
                    preset, supported_modes, korean_locale=locale == "ko"
                ),
                action="create",
            )
        )

        if has_fonts_css:
            ops.append(
                FileOp(
                    path="design-system/fonts.css",
                    content=_build_fonts_css(pairing),
                    action="create",
                )
            )
            ops.extend(
                pretendard_asset_ops(
                    assets_dir="design-system/fonts",
                    fetch_script_path="design-system/fonts/fetch-pretendard.mjs",
                )
            )

        ops.append(
            FileOp(
                path="design-system/README.md",
                content=_build_readme(preset.id, has_fonts_css),
                action="create",
            )
        )

        ops.extend(design_system_mirror_ops(preset))

        return ops

    def merge(self, op: FileOp, existing_path: Path) -> FileOp:
        path = op.path
        try:
            existing = existing_path.read_text(encoding="utf-8")
        except (FileNotFoundError, UnicodeDecodeError):
            return FileOp(
                path=f"{path}.ds-proposed",
                content=op.content,
                action="proposed",
                reason="unreadable existing file",
                original_path=path,
            )

        if path in ("design-system/tokens.css", "design-system/fonts.css"):
            if DS_BLOCK_START not in existing or DS_BLOCK_END not in existing:
                return FileOp(
                    path=f"{path}.ds-proposed",
                    content=op.content,
                    action="proposed",
                    reason=f"existing {path} has no design-ontology managed block",
                    original_path=path,
                )
            start = op.content.find(DS_BLOCK_START)
            end = op.content.find(DS_BLOCK_END)
            if start == -1 or end == -1:
                return FileOp(
                    path=f"{path}.ds-proposed",
                    content=op.content,
                    action="proposed",
                    reason="generated block markers missing",
                    original_path=path,
                )
            new_body = op.content[start + len(DS_BLOCK_START) : end].strip()
            updated, _ = replace_managed_block(existing, new_body)
            return FileOp(path=path, content=updated, action="merge")

        # design-system/ 나머지는 generator-owned → overwrite.
        if path.startswith("design-system/"):
            return FileOp(path=path, content=op.content, action="overwrite")

        # Raw 어댑터는 user repo 최상위를 건드리지 않음.
        return FileOp(
            path=f"{path}.ds-proposed",
            content=op.content,
            action="proposed",
            reason="raw-css-variables does not modify files outside design-system/",
            original_path=path,
        )
